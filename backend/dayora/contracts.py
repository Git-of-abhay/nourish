from typing import Protocol


class ProfileRepository(Protocol):
    def insert_profile(self, data: dict) -> None: ...
    def profile_by_token_hash(self, token_hash: str) -> dict | None: ...
    def update_profile(self, profile_id: str, data: dict) -> dict: ...


class MealRepository(Protocol):
    def insert_meal(self, data: dict) -> dict: ...


class WorkoutRepository(Protocol):
    def insert_workout(self, data: dict) -> dict: ...


class ReportRepository(Protocol):
    def insert_report(self, data: dict) -> dict: ...


class ImageAnalyzer(Protocol):
    def analyze_meal(self, content: bytes, mime: str) -> dict: ...
    def analyze_report(self, content: bytes, mime: str) -> dict: ...
